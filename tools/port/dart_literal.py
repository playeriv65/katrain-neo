"""Write Python values as Dart constant expressions, for the generated parts of katrain_core."""

import math
import re


def dart_string(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or 0x7F <= ord(ch) < 0xA0 or ch in "​ㅤ﻿":
            # control and invisible characters (KaTrain's comment markers) are spelled out
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return "'" + "".join(out) + "'"


def dart_value(v, indent="") -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if math.isnan(v):
            return "double.nan"
        if math.isinf(v):
            return "double.infinity" if v > 0 else "double.negativeInfinity"
        return repr(v)
    if isinstance(v, str):
        return dart_string(v)
    if isinstance(v, range):
        v = list(v)
    if isinstance(v, tuple):
        return "(" + ", ".join(dart_value(x, indent) for x in v) + ("," if len(v) == 1 else "") + ")"
    inner = indent + "  "
    if isinstance(v, list):
        if not v:
            return "[]"
        return "[\n" + "".join(f"{inner}{dart_value(x, inner)},\n" for x in v) + indent + "]"
    if isinstance(v, (set, frozenset)):
        return "{\n" + "".join(f"{inner}{dart_value(x, inner)},\n" for x in sorted(v)) + indent + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        return "{\n" + "".join(f"{inner}{dart_value(k, inner)}: {dart_value(x, inner)},\n" for k, x in v.items()) + indent + "}"
    raise TypeError(f"cannot write {type(v)} as Dart: {v!r}")


def camel(name: str) -> str:
    """UPPER_SNAKE (Python constant) to lowerCamel (Dart constant)."""
    parts = name.lower().split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def header(source: str, script: str) -> str:
    return (
        f"// GENERATED by {script} from KaTrain's {source} (https://github.com/sanderland/katrain, MIT).\n"
        "// Do not edit; regenerate instead.\n"
        "// ignore_for_file: lines_longer_than_80_chars\n\n"
    )


def file_name(s: str) -> str:
    return re.sub(r"[^a-z0-9_]", "_", s.lower())
